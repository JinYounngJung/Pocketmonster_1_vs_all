// Instantiation helper
export function createPokemonInstance(raw: RawPokemonDef): PokemonData {
  const stats = calculateLv50Stats(raw.baseStats);
  const moves: Move[] = raw.moveKeys.map((key) => {
    const moveDef = MOVES_DATABASE[key] || MOVES_DATABASE.body_slam;
    return { ...moveDef, pp: moveDef.maxPp };
  });

  return {
    id: raw.id,
    dexNumber: raw.dexNumber,
    name: raw.name,
    nameEn: raw.nameEn,
    types: [...raw.types],
    baseStats: { ...raw.baseStats },
    stats: { ...stats },
    moves,
    currentHp: stats.hp,
    ability: { ...raw.ability },
    spriteFront: `https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon/${raw.dexNumber}.png`,
    spriteBack: `https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon/back/${raw.dexNumber}.png`,
    officialArtwork: `https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon/other/official-artwork/${raw.dexNumber}.png`,
    status: 'none',
    statusTurns: 0,
    statStages: {
      attack: 0,
      defense: 0,
      spAttack: 0,
      spDefense: 0,
      speed: 0,
      accuracy: 0,
      evasion: 0,
    },
  };
}

export const ALL_PLAYABLE_POKEMON: PokemonData[] = ALL_POKEMON_DEFS.map(createPokemonInstance);

export function getPokemonById(id: string): PokemonData {
  const found = ALL_POKEMON_DEFS.find((p) => p.id === id);
  if (!found) {
    return createPokemonInstance(ALL_POKEMON_DEFS[0]);
  }
  return createPokemonInstance(found);
}
