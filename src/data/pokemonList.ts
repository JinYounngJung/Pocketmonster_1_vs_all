// Formula to calculate competitive Lv 50 stats (Assuming 31 IVs and balanced EVs)
export function calculateLv50Stats(base: BaseStats): BaseStats {
  const level = 50;
  const iv = 31;
  const ev = 84; // roughly 21 stat points

  const hp = Math.floor(((2 * base.hp + iv + Math.floor(ev / 4)) * level) / 100) + level + 10;
  const attack = Math.floor(((2 * base.attack + iv + Math.floor(ev / 4)) * level) / 100) + 5;
  const defense = Math.floor(((2 * base.defense + iv + Math.floor(ev / 4)) * level) / 100) + 5;
  const spAttack = Math.floor(((2 * base.spAttack + iv + Math.floor(ev / 4)) * level) / 100) + 5;
  const spDefense = Math.floor(((2 * base.spDefense + iv + Math.floor(ev / 4)) * level) / 100) + 5;
  const speed = Math.floor(((2 * base.speed + iv + Math.floor(ev / 4)) * level) / 100) + 5;

  return { hp, attack, defense, spAttack, spDefense, speed };
}

